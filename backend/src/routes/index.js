api.get('/health', async (_req, res) => {
  let mlOk = false;
  let rfReady = false;
  try {
    const h = await ml.health();
    mlOk = h.status === 'ok';
    rfReady = Boolean(h.rf_ready);
  } catch { /* ML down is a degraded state, not a crash */ }
  res.json({
    status: 'ok',
    ml: mlOk,
    randomForestTrained: rfReady,
    // Surfaced so the UI can show a persistent banner. Audit R5/R6/R8: a demo
    // screenshot must never be mistakable for a result.
    demoMode: config.demoMode,
    demoNotice: config.demoMode
      ? 'Demonstration mode. Availability comes from a deterministic schedule '
        + 'lookup, not a trained Random Forest. Answers are composed from '
        + 'templates over retrieved text, not generated by Llama 3.1 8B. '
        // Campus locations stopped being placeholders when the real 28 were
        // imported, and saying otherwise would understate the data in a
        // document about data provenance. Their limitation is different and
        // more specific: traced from imagery, not surveyed on site.
        + 'Faculty data are placeholders. Campus locations are real but their '
        + 'coordinates were traced from satellite imagery, not surveyed on '
        + 'site as thesis §3.4.1(a) requires.'
      : null,
  });
});

const historySchema = z.array(z.object({
  role: z.enum(['user', 'assistant']),
  content: z.string().max(600),
})).max(12).optional();

const chatSchema = z.object({
  query: z.string().min(2).max(500),
  // Capped at the edge as well as sanitised in the pipeline: the schema stops
  // a client posting a megabyte of "history" into a prompt, and
  // sanitiseHistory decides what of it may actually be replayed.
  history: historySchema,
  // NOTE the absence of `mode`. Audit F-16: the standard/enhanced switch is an
  // evaluation concern. Exposed publicly it would let anyone drive the
  // baseline arm and would make evaluation runs indistinguishable from live
  // traffic in the logs. This endpoint is hard-wired to `enhanced`.
});

api.post('/chat', optionalAuth, limit(config.rateLimit.chatMax), async (req, res, next) => {
  try {
    const { query, history } = chatSchema.parse(req.body);

    // Audit F-29. Availability requires a campus account; the map and
    // institutional Q&A stay open. Masking protects the granularity of one
    // answer but does nothing about volume, so an anonymous availability
    // endpoint can be polled into a presence timeline. Attaching a person to
    // the query makes that attributable and rate-limitable.
    const signedIn = Boolean(req.user);

    // Present-moment only, for everyone. No historical lookups ("was she in
    // yesterday") and no forecasting ("when will she be free") — either turns
    // a generalized status into a movement profile.
    const result = await runPipeline({
      query,
      mode: 'enhanced',
      at: new Date(),
      allowAvailability: signedIn,
      history,
    });
    result.route.query = query;

    await logChat(result, { sessionHash: sessionHash(req) });
    const dto = assertNoLeak(toChatDto(result));
    dto.authRequired = result.availabilityWithheld ?? false;
    res.json(dto);
  } catch (err) {
    next(err);
  }
});

/**
 * Landing-page comparison widget (audit open decision 3).
 *
 * Runs both arms so visitors can see what Context Fusion actually adds — the
 * best demonstration of the study's contribution available. It preserves the
 * F-16 invariant by accepting ONLY curated queries: `mode` is still not a
 * client-controlled parameter on free text, and a fixed query list cannot be
 * polled to reconstruct anyone's presence timeline (F-29).
 */
api.get('/demo/queries', limit(config.rateLimit.generalMax), async (_req, res, next) => {
  try {
    const { data, error } = await db
      .from('demo_query')
      .select('id, label, query_text, category')
      .eq('is_active', true)
      .order('sort_order');
    if (error) throw error;
    res.json({ queries: data ?? [] });
  } catch (err) { next(err); }
});

api.post('/demo/compare', limit(config.rateLimit.demoMax), async (req, res, next) => {
  try {
    // Not .uuid(): the value is looked up against the demo_query allowlist
    // below, so the table is the authority on what is acceptable, not the
    // id format. Demo-mode fixtures use short ids.
    const { demoQueryId } = z.object({ demoQueryId: z.string().min(1).max(64) }).parse(req.body);

    const { data: demo, error } = await db
      .from('demo_query')
      .select('query_text, category')
      .eq('id', demoQueryId)
      .eq('is_active', true)
      .maybeSingle();
    if (error) throw error;
    if (!demo) return res.status(404).json({ error: 'unknown demo query' });

    // allowAvailability is on here despite being a public endpoint: the query
    // list is curated and fixed (audit F-16), so it cannot be repurposed to
    // poll an arbitrary person's status.
    const [standard, enhanced] = await Promise.all([
      runPipeline({ query: demo.query_text, mode: 'standard', allowAvailability: true }),
      runPipeline({ query: demo.query_text, mode: 'enhanced', allowAvailability: true }),
    ]);

    for (const r of [standard, enhanced]) {
      r.route.query = demo.query_text;
      await logChat(r, { sessionHash: sessionHash(req), isDemo: true });
    }

    res.json({
      query: demo.query_text,
      category: demo.category,
      standard: assertNoLeak(toChatDto(standard)),
      enhanced: assertNoLeak(toChatDto(enhanced)),
      // Context Fusion breakdown — what the enhanced arm added, structurally.
      fusion: {
        retrievedChunks: enhanced.sources.length,
        statusInjected: Boolean(enhanced.masked),
        statusLabel: enhanced.statusLabel,
        contextItems: enhanced.contextsForRagas.length,
      },
      // Audit R8: a single demo timing is NOT a research measurement. Response
      // Time figures come from evalRunner, interleaved, median and p95.
      timingNote: 'Illustrative only — not a research measurement.',
    });
  } catch (err) { next(err); }
});

