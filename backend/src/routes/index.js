api.post('/demo/compare', limit(config.rateLimit.demoMax), async (req, res, next) => {
  try {
    // Not .uuid(): the value is looked up against the demo_query allowlist
    // below, so the table is the authority on what is acceptable, not the
    // id format. Demo-mode fixtures use short ids.
    const { demoQueryId } = z.object({ demoQueryId: z.string().min(1).max(64) }).parse(req.body);

    const { data: demo, error } = await db
      .from('demo_query')
      .select('query_text, category')
      .eq('id', demoQueryId)
      .eq('is_active', true)
      .maybeSingle();
    if (error) throw error;
    if (!demo) return res.status(404).json({ error: 'unknown demo query' });

    // allowAvailability is on here despite being a public endpoint: the query
    // list is curated and fixed (audit F-16), so it cannot be repurposed to
    // poll an arbitrary person's status.
    const [standard, enhanced] = await Promise.all([
      runPipeline({ query: demo.query_text, mode: 'standard', allowAvailability: true }),
      runPipeline({ query: demo.query_text, mode: 'enhanced', allowAvailability: true }),
    ]);

    for (const r of [standard, enhanced]) {
      r.route.query = demo.query_text;
      await logChat(r, { sessionHash: sessionHash(req), isDemo: true });
    }

    res.json({
      query: demo.query_text,
      category: demo.category,
      standard: assertNoLeak(toChatDto(standard)),
      enhanced: assertNoLeak(toChatDto(enhanced)),
      // Context Fusion breakdown — what the enhanced arm added, structurally.
      fusion: {
        retrievedChunks: enhanced.sources.length,
        statusInjected: Boolean(enhanced.masked),
        statusLabel: enhanced.statusLabel,
        contextItems: enhanced.contextsForRagas.length,
      },
      // Audit R8: a single demo timing is NOT a research measurement. Response
      // Time figures come from evalRunner, interleaved, median and p95.
      timingNote: 'Illustrative only — not a research measurement.',
    });
  } catch (err) { next(err); }
});

