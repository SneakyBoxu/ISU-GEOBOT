api.get('/faculty/search', limit(config.rateLimit.generalMax), async (req, res, next) => {
  try {
    const q = String(req.query.q ?? '').trim();
    if (q.length < 2) return res.json({ candidates: [] });

    const { data, error } = await db.rpc('resolve_faculty_candidates', {
      p_needle: q,
      p_limit: 5,
    });
    if (error) throw error;
    res.json({
      // Audit F-31: returns ALL candidates. The caller asks when there is more
      // than one; it never auto-selects a winner.
      candidates: (data ?? []).map((c) => ({
        id: c.faculty_id,
        name: c.full_name,
        department: c.department_name,
        matchKind: c.match_kind,
      })),
    });
  } catch (err) { next(err); }
});

