const chatSchema = z.object({
  query: z.string().min(2).max(500),
  // Capped at the edge as well as sanitised in the pipeline: the schema stops
  // a client posting a megabyte of "history" into a prompt, and
  // sanitiseHistory decides what of it may actually be replayed.
  history: historySchema,
  // NOTE the absence of `mode`. Audit F-16: the standard/enhanced switch is an
  // evaluation concern. Exposed publicly it would let anyone drive the
  // baseline arm and would make evaluation runs indistinguishable from live
  // traffic in the logs. This endpoint is hard-wired to `enhanced`.
});

api.post('/chat', optionalAuth, limit(config.rateLimit.chatMax), async (req, res, next) => {
  try {
    const { query, history } = chatSchema.parse(req.body);

    // Audit F-29. Availability requires a campus account; the map and
    // institutional Q&A stay open. Masking protects the granularity of one
    // answer but does nothing about volume, so an anonymous availability
    // endpoint can be polled into a presence timeline. Attaching a person to
    // the query makes that attributable and rate-limitable.
    const signedIn = Boolean(req.user);

    // Present-moment only, for everyone. No historical lookups ("was she in
    // yesterday") and no forecasting ("when will she be free") — either turns
    // a generalized status into a movement profile.
    const result = await runPipeline({
      query,
      mode: 'enhanced',
      at: new Date(),
      allowAvailability: signedIn,
      history,
    });
    result.route.query = query;

    await logChat(result, { sessionHash: sessionHash(req) });
    const dto = assertNoLeak(toChatDto(result));
    dto.authRequired = result.availabilityWithheld ?? false;
    res.json(dto);
  } catch (err) {
    next(err);
  }
});

