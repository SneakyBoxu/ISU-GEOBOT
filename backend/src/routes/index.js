// Audit F-29: session identity is a SALTED HASH, never a raw IP. The chat log
// exists to detect abuse, not to build a record of who asked what.
function sessionHash(req) {
  return crypto
    .createHash('sha256')
    .update(`${req.ip}:${req.headers['user-agent'] ?? ''}:${config.sessionSalt}`)
    .digest('hex')
    .slice(0, 32);
}

