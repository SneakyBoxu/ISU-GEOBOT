/**
 * Evaluation status for the UI.
 *
 * Audit R6/R7/R8 and brief §2.7: metric cards render an EMPTY STATE until a
 * real run exists. There is no placeholder number anywhere in this response,
 * because a placeholder number is one screenshot away from becoming evidence.
 */
api.get('/eval/status', async (_req, res, next) => {
  try {
    if (config.demoMode) {
      // Audit R7/R8. There is nothing to report and there never will be from
      // demo mode. Saying so explicitly beats returning an empty list that
      // could read as "evaluated, scored zero".
      return res.json({
        hasResults: false,
        runs: [],
        scoredResults: 0,
        activeModel: null,
        demoMode: true,
        disclaimer:
          'Demonstration mode. No evaluation can be run against placeholder '
          + 'data: the harness refuses synthetic rows by design. RAGAS scores, '
          + 'classification accuracy and faculty validation results will appear '
          + 'only after real evaluation runs against real institutional data.',
      });
    }
    const { data: runs } = await db
      .from('eval_run')
      .select('id, run_label, started_at, finished_at, groq_model_id, judge_model, top_k')
      .order('started_at', { ascending: false })
      .limit(5);

    const { count: scored } = await db
      .from('ragas_score')
      .select('id', { count: 'exact', head: true });

    const { data: models } = await db
      .from('rf_model_version')
      .select('version, trained_at, label_source, split_strategy')
      .order('trained_at', { ascending: false })
      .limit(1);

    res.json({
      hasResults: Boolean(scored),
      runs: runs ?? [],
      scoredResults: scored ?? 0,
      activeModel: models?.[0] ?? null,
      disclaimer:
        'ISU-GeoBot is a research prototype. No evaluation results have been ' +
        'published for this deployment. RAGAS scores, classification accuracy ' +
        'and faculty validation figures will appear here only after real ' +
        'evaluation runs have been completed and recorded.',
    });
  } catch (err) { next(err); }
});

