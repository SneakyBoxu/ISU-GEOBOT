api.get('/validate/context', requireAuth, requireRole('validator', 'admin', 'researcher'),
  async (req, res, next) => {
    try {
      // In-system capture (audit C14): the system records its OWN prediction,
      // so a validator cannot misremember what it said. That removes a
      // transcription-error attack on the results.
      let targetFacultyId = req.query.facultyId || req.user.facultyId;
      if (!targetFacultyId && req.user.roles.some((r) => ['admin', 'researcher'].includes(r))) {
        try {
          const { data: anyFaculty } = await db
            .from('faculty')
            .select('id')
            .eq('is_active', true)
            .limit(1)
            .maybeSingle();
          targetFacultyId = anyFaculty?.id ?? null;
        } catch {
          const snap = getMemorySnapshot();
          targetFacultyId = snap?.faculty?.[0]?.id ?? null;
        }
      }

      const defaultStatusOptions = [
        { code: 'available_consultation', display_label: 'Available for Consultation' },
        { code: 'in_scheduled_class', display_label: 'In Scheduled Class' },
        { code: 'unavailable_off_schedule', display_label: 'Unavailable / Off Schedule' },
      ];

      if (!targetFacultyId) {
        let statuses = defaultStatusOptions;
        try {
          const { data } = await db
            .from('availability_status')
            .select('code, display_label')
            .order('sort_order');
          if (data?.length) statuses = data;
        } catch { /* use default */ }

        return res.json({
          faculty: null,
          systemStatus: null,
          systemStatusLabel: null,
          overrideApplied: false,
          estimatedAt: null,
          statusOptions: statuses,
        });
      }

      let faculty = null;
      try {
        const { data } = await db
          .from('faculty')
          .select('id, full_name')
          .eq('id', targetFacultyId)
          .maybeSingle();
        faculty = data;
      } catch (err) {
        const snap = getMemorySnapshot();
        const f = snap?.faculty?.find((x) => x.id === targetFacultyId);
        if (f) faculty = { id: f.id, name: f.full_name, full_name: f.full_name };
      }

      let systemStatus = null;
      let systemStatusLabel = null;
      let overrideApplied = false;
      let estimatedAt = null;

      try {
        const avail = await getAvailability(targetFacultyId);
        if (avail?.masked?.statusCode) {
          systemStatus = avail.masked.statusCode;
          systemStatusLabel = await labelFor(avail.masked.statusCode);
          if (systemStatus === 'unavailable_off_schedule' && avail.scheduleContext?.onOtherCampus) {
            systemStatusLabel = 'Teaching this period; not scheduled on this campus';
          }
          overrideApplied = Boolean(avail.overrideApplied);
          estimatedAt = avail.masked.maskedAt ?? new Date().toISOString();
        }
      } catch (err) {
        log.warn({ err: err.message, targetFacultyId }, 'Could not resolve availability estimate for validation context');
      }

      let statuses = defaultStatusOptions;
      try {
        const { data } = await db
          .from('availability_status')
          .select('code, display_label')
          .order('sort_order');
        if (data?.length) statuses = data;
      } catch { /* use default */ }

      res.json({
        faculty: faculty ? { id: faculty.id, name: faculty.full_name || faculty.name } : null,
        systemStatus,
        systemStatusLabel,
        overrideApplied,
        estimatedAt,
        statusOptions: statuses,
      });
    } catch (err) { next(err); }
  });

