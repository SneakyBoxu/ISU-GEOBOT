/**
 * HTTP surface.
 *
 * Boundary rules enforced here (audit Section F):
 *   1. Groq is called only from the server. The key never leaves it.
 *   2. Flask is never exposed publicly.
 *   3. The frontend never holds the Supabase service_role key.
 *   4. /api/chat CANNOT select the standard arm.
 *   5. Every response body is an explicit allowlist.
 */

