const eventSchema = z.object({
  // Not .uuid(): the real authorization check is the consented-roster lookup
  // below (audit W3), not the identifier format. Demo fixtures use short ids.
  facultyId: z.string().min(1).max(64),
  eventType: z.enum(['arrival', 'departure']),
  note: z.string().max(280).optional(),
  supersedesId: z.string().min(1).max(64).optional(),
});

api.post('/guard/events', requireAuth, requireRole('guard'),
  async (req, res, next) => {
    try {
      const body = eventSchema.parse(req.body);

      const { data: guard } = await db
        .from('guard_user')
        .select('id')
        .eq('auth_user_id', req.user.id)
        .eq('is_active', true)
        .maybeSingle();
      if (!guard) return res.status(403).json({ error: 'no active guard record' });

      // Audit W3 (IDOR): consented roster only.
      const { data: faculty } = await db
        .from('faculty')
        .select('id')
        .eq('id', body.facultyId)
        .eq('is_consented', true)
        .eq('is_active', true)
        .maybeSingle();
      if (!faculty) {
        return res.status(403).json({ error: 'faculty is not on the consented roster' });
      }

      const { data, error } = await db
        .from('guard_presence_event')
        .insert({
          faculty_id: body.facultyId,
          event_type: body.eventType,
          logged_by: guard.id,
          note: body.note ?? null,
          supersedes_id: body.supersedesId ?? null,
          data_origin: 'real',
        })
        .select('id, occurred_at')
        .single();
      if (error) throw error;

      const presence = await resolvePresence(body.facultyId);
      res.status(201).json({ event: data, presenceState: presence.state });
    } catch (err) { next(err); }
  });

