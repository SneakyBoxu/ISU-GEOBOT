api.post('/guard/events', requireAuth, requireRole('guard', 'admin', 'researcher'),
  async (req, res, next) => {
    try {
      const body = eventSchema.parse(req.body);

      let { data: guard } = await db
        .from('guard_user')
        .select('id')
        .eq('auth_user_id', req.user.id)
        .eq('is_active', true)
        .maybeSingle();

      // If user is admin/researcher and does not have a guard_user record yet, auto-provision one
      if (!guard && req.user.roles.some((r) => ['admin', 'researcher', 'guard'].includes(r))) {
        const { data: newGuard, error: guardErr } = await db
          .from('guard_user')
          .upsert({
            auth_user_id: req.user.id,
            display_name: req.user.email ? req.user.email.split('@')[0] : 'Administrator',
            is_active: true,
          }, { onConflict: 'auth_user_id' })
          .select('id')
          .single();
        if (!guardErr && newGuard) {
          guard = newGuard;
        }
      }

      if (!guard) return res.status(403).json({ error: 'no active guard record' });

      // Audit W3 (IDOR): consented roster only.
      const { data: faculty } = await db
        .from('faculty')
        .select('id')
        .eq('id', body.facultyId)
        .eq('is_consented', true)
        .eq('is_active', true)
        .maybeSingle();
      if (!faculty) {
        return res.status(403).json({ error: 'faculty is not on the consented roster' });
      }

      const { data, error } = await db
        .from('guard_presence_event')
        .insert({
          faculty_id: body.facultyId,
          event_type: body.eventType,
          logged_by: guard.id,
          note: body.note ?? null,
          supersedes_id: body.supersedesId ?? null,
          data_origin: 'real',
        })
        .select('id, occurred_at')
        .single();
      if (error) throw error;

      const presence = await resolvePresence(body.facultyId);
      res.status(201).json({ event: data, presenceState: presence.state });
    } catch (err) { next(err); }
  });

