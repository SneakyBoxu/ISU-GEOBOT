api.get('/validate/context', requireAuth, requireRole('validator'),
  async (req, res, next) => {
    try {
      // In-system capture (audit C14): the system records its OWN prediction,
      // so a validator cannot misremember what it said. That removes a
      // transcription-error attack on the results.
      const { data: faculty } = await db
        .from('faculty')
        .select('id, full_name')
        .eq('id', req.user.facultyId)
        .maybeSingle();

      const result = await runPipeline({
        query: `Is ${faculty?.full_name} available right now?`,
        mode: 'enhanced',
        allowAvailability: true,
      });

      const { data: statuses } = await db
        .from('availability_status')
        .select('code, display_label')
        .order('sort_order');

      res.json({
        faculty: { id: faculty?.id, name: faculty?.full_name },
        systemStatus: result.masked?.statusCode ?? null,
        systemStatusLabel: result.statusLabel,
        overrideApplied: result.overrideApplied,
        estimatedAt: result.masked?.maskedAt ?? null,
        statusOptions: statuses ?? [],
      });
    } catch (err) { next(err); }
  });

